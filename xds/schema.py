"""Emit the TypeScript types for @xds/protocol from the Pydantic models, or check they are current.

`xds schema --emit-types` writes packages/protocol/src/generated/project.ts with
json-schema-to-typescript; `--check` fails when the checked-in file differs.
"""

from __future__ import annotations

import json
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from pydantic.json_schema import models_json_schema

from .models import EXPORTED_TYPES

REPO = Path(__file__).resolve().parent.parent
GENERATED = REPO / "packages" / "protocol" / "src" / "generated" / "project.ts"
HEADER = "/* Generated by `uv run xds schema --emit-types` from xds/models.py. Do not edit. */\n"


def _clean(node: Any, *, keep_title: bool = False) -> Any:
    """Shape the schema for readable TypeScript.

    - draft-7 tuples (`items: [...]`), which json-schema-to-typescript reads, not `prefixItems`;
    - `X | None = None` becomes an optional `x?: X` (files omit nulls; `to_json` drops them);
    - property titles are dropped so types are inlined instead of named `Name1`, `Id3`, ….
    """
    if isinstance(node, list):
        return [_clean(v) for v in node]
    if not isinstance(node, dict):
        return node
    node = dict(node)
    if not keep_title:
        node.pop("title", None)
    if "prefixItems" in node:
        node["items"] = node.pop("prefixItems")
        node["additionalItems"] = False
    if "anyOf" in node:
        branches = [b for b in node["anyOf"] if b != {"type": "null"}]
        if len(branches) != len(node["anyOf"]):
            node.pop("default", None)
            if len(branches) == 1:
                node.pop("anyOf")
                node.update(branches[0])
            else:
                node["anyOf"] = branches
    out = {}
    for k, v in node.items():
        if k in ("properties", "definitions", "$defs"):
            out[k] = {name: _clean(sub, keep_title=(k != "properties")) for name, sub in v.items()}
        else:
            out[k] = _clean(v)
    return out


def json_schema() -> dict[str, Any]:
    _, top = models_json_schema([(m, "validation") for m in EXPORTED_TYPES], by_alias=True,
                                ref_template="#/definitions/{model}")
    defs = top.get("$defs", {})
    return _clean({
        "title": "XdsSchema",
        "type": "object",
        "additionalProperties": False,
        "properties": {m.__name__[0].lower() + m.__name__[1:]: {"$ref": f"#/definitions/{m.__name__}"}
                       for m in EXPORTED_TYPES},
        "definitions": defs,
    }, keep_title=True)


def render_types() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "schema.json"
        src.write_text(json.dumps(json_schema(), indent=2))
        out = subprocess.run(
            ["npx", "--no-install", "json2ts", "-i", str(src), "--unreachableDefinitions",
             "--no-additionalProperties", "--bannerComment", HEADER.strip(), "--format", "true"],
            cwd=REPO, capture_output=True, text=True, check=True)
    return out.stdout


def emit() -> Path:
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(render_types())
    return GENERATED


def check() -> bool:
    return GENERATED.exists() and GENERATED.read_text() == render_types()
